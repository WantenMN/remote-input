package banner

import (
	"fmt"
	"io"
	"net/netip"
	"strings"

	qrcode "github.com/skip2/go-qrcode"
)

const (
	bold   = "\x1b[1m"
	dim    = "\x1b[2m"
	cyan   = "\x1b[36m"
	green  = "\x1b[32m"
	yellow = "\x1b[33m"
	reset  = "\x1b[0m"
)

func Print(w io.Writer, ip netip.Addr, port uint16, useHTTP bool) {
	scheme := "https"
	if useHTTP {
		scheme = "http"
	}
	url := fmt.Sprintf("%s://%s:%d", scheme, ip, port)

	fmt.Fprintln(w)
	fmt.Fprintf(w, "  %s%sRemote Input%s\n", bold, cyan, reset)
	fmt.Fprintln(w)
	fmt.Fprintf(w, "  %sOpen on your phone:%s\n", green, reset)
	fmt.Fprintf(w, "  %s→%s %s%s%s\n", green, reset, bold, url, reset)
	fmt.Fprintln(w)

	if useHTTP {
		fmt.Fprintf(w, "  %s⚠ Running in HTTP mode (unencrypted).%s\n", yellow, reset)
		fmt.Fprintf(w, "  %s  Traffic can be intercepted on the LAN.%s\n", dim, reset)
		fmt.Fprintf(w, "  %s  Remove --http to use HTTPS instead.%s\n", dim, reset)
	} else {
		fmt.Fprintf(w, "  %sThe browser may warn that the certificate is untrusted.%s\n", dim, reset)
		fmt.Fprintf(w, "  %sThis is normal — it is a self-signed cert generated by%s\n", dim, reset)
		fmt.Fprintf(w, "  %sthis program. Your input is encrypted and private.%s\n", dim, reset)
	}

	fmt.Fprintln(w)
	fmt.Fprintf(w, "  %sScan QR code:%s\n", dim, reset)
	if qr, err := qrcode.New(url, qrcode.Medium); err == nil {
		for _, line := range renderTerminal(qr) {
			fmt.Fprintf(w, "  %s\n", line)
		}
	}
	fmt.Fprintln(w)
	fmt.Fprintf(w, "  %sWaiting for connection...%s\n", dim, reset)
	fmt.Fprintln(w)
}

func renderTerminal(qr *qrcode.QRCode) []string {
	const border = 2

	bitmap := qr.Bitmap()
	size := len(bitmap) + 2*border

	at := func(x, y int) bool {
		x -= border
		y -= border
		if x < 0 || y < 0 || x >= len(bitmap) || y >= len(bitmap) {
			return false
		}
		return bitmap[y][x]
	}

	lines := make([]string, 0, (size+1)/2)
	for y := 0; y < size; y += 2 {
		var b strings.Builder
		b.WriteString("\x1b[30;47m")
		for x := 0; x < size; x++ {
			top := at(x, y)
			bottom := y+1 < size && at(x, y+1)
			switch {
			case top && bottom:
				b.WriteString("█")
			case top:
				b.WriteString("▀")
			case bottom:
				b.WriteString("▄")
			default:
				b.WriteString(" ")
			}
		}
		b.WriteString(reset)
		lines = append(lines, b.String())
	}
	return lines
}
